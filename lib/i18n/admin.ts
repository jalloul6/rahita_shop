export const adminDictionaries = { en, ar } as const;
export type AdminLocale = keyof typeof adminDictionaries;

export function isAdminLocale(value: unknown): value is AdminLocale {
  return value === "en" || value === "ar";
}

// Translates an English validation message (lib/validators.ts) for the Arabic dashboard.
// Messages built by number() ("Price must be a number") are matched by pattern.
export function translateValidation(message: string | undefined, t: AdminDict): string | undefined {
  if (!message || t === en) return message;
  const exact = t.validation[message];
  if (exact) return exact;
  const m = message.match(/^(.+?) (is required|must be a number|cannot be negative|is too large|must be a whole number)$/);
  if (m) {
    const label = t.fieldLabels[m[1]] ?? m[1];
    const rule: Record<string, string> = {
      "is required": "مطلوب",
      "must be a number": "يجب أن يكون رقماً",
      "cannot be negative": "لا يمكن أن يكون سالباً",
      "is too large": "كبير جداً",
      "must be a whole number": "يجب أن يكون عدداً صحيحاً",
    };
    return `${label} ${rule[m[2]]}`;
  }
  return message;
}

// Zod issues joined into one translated message, one per line.
export function issuesMessage(issues: { message: string }[], t: AdminDict) {
  return issues.map((i) => translateValidation(i.message, t)).join("\n");
}
